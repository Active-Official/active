#[test]
fn rust_output_parses_as_valid_syntax() {
    let rust = schema_to_rust(&module(), "Config").expect("generate");
    for probe in [
        "pub struct Config {",
        "pub port: i64,",
        "pub host: Option<String>,",
        "pub mode: ConfigMode,",
        "pub tags: Vec<String>,",
        "pub server: ConfigServer,",
        "pub struct ConfigServer {",
        "pub enum ConfigMode {",
        "#[deprecated(note = \"use new\")]",
    ] {
        assert!(rust.contains(probe), "missing {probe}:\n{rust}");
    }
    // Syntax gate: rustfmt parses what serde would compile (plain
    // format run — success means the syntax is valid; --check would
    // additionally demand canonical formatting, which is not the
    // generated style).
    let dir = std::env::temp_dir().join("active-gen-tests");
    std::fs::create_dir_all(&dir).expect("temp dir");
    let path = dir.join("generated.rs");
    std::fs::write(&path, &rust).expect("write");
    let out = std::process::Command::new("rustfmt")
        .args(["--edition", "2021"])
        .arg(&path)
        .output()
        .expect("run rustfmt");
    assert!(
        out.status.success(),
        "generated Rust must parse: {}",
        String::from_utf8_lossy(&out.stderr)
    );
}

#[test]
fn generation_fails_without_a_schema() {
    let module = parse("port = 1\n", "generate").expect("must parse");
    for result in [
        schema_to_json_schema(&module).map(|_| ()),
        schema_to_openapi(&module, "X").map(|_| ()),
        schema_to_typescript(&module, "X").map(|_| ()),
        schema_to_go(&module, "X").map(|_| ()),
        schema_to_rust(&module, "X").map(|_| ()),
    ] {
        assert!(result.is_err(), "schema-less documents must fail");
    }
}

#[test]
fn dynamic_bounds_skip_without_diagnostics() {
    // A computed bound has no static form: skipped, still valid.
    let module = parse(
        "let cap = 10\nschema = { port = Int(max = cap) }\nport = 1\n",
        "generate",
    )
    .expect("must parse");
    let schema = schema_to_json_schema(&module).expect("generate");
    assert!(schema["properties"]["port"].get("maximum").is_none());
}

#[test]
fn colliding_type_names_suffix_deterministically() {
    // `port` and `Port` tables derive the same base: references and
    // declarations must agree on the suffixed split.
    let module = parse(
        "schema = { port = Table { x = Int }, Port = Table { y = Int } }\n",
        "generate",
    )
    .expect("must parse");
    for output in [
        schema_to_typescript(&module, "Config").expect("ts"),
        schema_to_go(&module, "Config").expect("go"),
        schema_to_rust(&module, "Config").expect("rust"),
    ] {
        assert!(output.contains("ConfigPort"), "{output}");
        assert!(output.contains("ConfigPort_"), "{output}");
    }
}

const EXT_SCHEMA_DOC: &str = r#"schema = {
  contact = String(format = "email", description = "Team inbox."),
  color = Enum("red", "green", descriptions = ["stop", "go"]),
  cert = String(requires = "tls"),
  tls = Bool(default = false),
}
"#;

#[test]
fn codegen_carries_new_schema_metadata() {
    let module = parse(EXT_SCHEMA_DOC, "generate").expect("schema must parse");
    let schema = schema_to_json_schema(&module).expect("jsonschema");
    let props = schema["properties"].as_object().expect("properties");
    assert_eq!(props["contact"]["format"], "email");
    assert_eq!(props["contact"]["description"], "Team inbox.");
    assert_eq!(props["color"]["description"], "red: stop; green: go");
    assert_eq!(
        schema["dependentRequired"],
        serde_json::json!({"tls": ["cert"]})
    );
    let ts = schema_to_typescript(&module, "Config").expect("ts");
    assert!(ts.contains("/** Team inbox. */"), "{ts}");
    let go = schema_to_go(&module, "Config").expect("go");
    assert!(go.contains("// Team inbox."), "{go}");
}

#[test]
fn python_target_escapes_and_dedupes() {
    let module = parse(
        "schema = { class = String(description = \"a\\nb\") }\n",
        "generate",
    )
    .expect("must parse");
    let py = schema_to_python(&module, "Config").expect("python");
    assert!(py.contains("class_: str"), "keyword gets underscore:\n{py}");
    assert!(py.contains("# a b"), "newline folded in comment:\n{py}");
}

#[test]
fn codegen_comments_cannot_inject_lines() {
    // A newline inside a description must fold to a space (never an
    // uncommented line), and `*/` must not close a TS block comment.
    // Mirrors the python_target_escapes_and_dedupes precedent for Go/TS.
    let module = parse(
        "schema = { hook = String(description = \"a\\nb */ c\", deprecated = \"x\\ny\", format = \"f\\ng\", requires = \"r\\ns\") }\n",
        "generate",
    )
    .expect("must parse");
    let go = schema_to_go(&module, "Config").expect("go");
    // Go uses `//` line comments: folding suffices, `*/` needs no
    // neutralization there (unlike TS block comments below).
    assert!(go.contains("// a b */ c"), "go folds comment:\n{go}");
    assert!(
        !go.lines().any(|l| l == "b * / c" || l == "b */ c"),
        "go emits no bare injected line:\n{go}"
    );
    assert!(go.contains("// Deprecated: x y"), "go folds reason:\n{go}");
    let ts = schema_to_typescript(&module, "Config").expect("ts");
    assert!(
        ts.contains("/** a b * / c */"),
        "ts neutralizes terminator:\n{ts}"
    );
    assert!(ts.contains("@deprecated x y"), "ts folds reason:\n{ts}");
    let py = schema_to_python(&module, "Config").expect("python");
    assert!(py.contains("# a b */ c"), "python folds comment:\n{py}");
    assert!(py.contains("# format: f g"), "python folds format:\n{py}");
    assert!(
        py.contains("# requires: r s"),
        "python folds requires:\n{py}"
    );
    assert!(
        !py.lines().any(|l| l == "b */ c" || l == "g" || l == "s"),
        "python emits no bare injected line:\n{py}"
    );
}

