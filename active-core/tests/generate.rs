#[test]
fn typescript_golden_snapshot() {
    let ts = schema_to_typescript(&module(), "Config").expect("generate");
    for probe in [
        "// Generated by Active",
        "(codegen v2)",
        "import { z } from \"zod\";",
        "export interface Config {",
        "port: number;",
        "host?: string;",
        "mode: \"a\" | \"b\";",
        "tags: string[];",
        "server: ConfigServer;",
        "token: string;",
        "export interface ConfigServer {",
        "/** @deprecated use new */",
        "export const ConfigSchema = z.object({",
        "export const ConfigServerSchema = z.object({",
        "z.enum([\"a\", \"b\"])",
        "server: ConfigServerSchema,",
    ] {
        assert!(ts.contains(probe), "missing {probe}:\n{ts}");
    }
    // Closed root table rejects unknown keys at runtime, exactly like
    // additionalProperties:false in JSON Schema and Active itself; the
    // open nested table stays lenient.
    assert!(ts.contains("}).strict();"), "{ts}");
    let server_schema = ts
        .split("export const ConfigServerSchema")
        .nth(1)
        .expect("server schema");
    assert!(
        !server_schema
            .split("export const ConfigSchema")
            .next()
            .expect("end")
            .contains(".strict()"),
        "{ts}"
    );
    // Zod schemas come after every interface they reference: children
    // first, so no const is read before initialization at module load.
    let server_pos = ts
        .find("ConfigServerSchema = z.object")
        .expect("server schema");
    let root_pos = ts.find("ConfigSchema = z.object").expect("root schema");
    assert!(server_pos < root_pos, "children-first order:\n{ts}");
}

