#[test]
fn codegen_is_byte_stable_across_runs() {
    // Determinism (CHECKLIST C.008): same input, same output, or it is
    // a bug. Every target generates twice; outputs must be identical.
    let module = parse(SCHEMA_DOC, "generate").expect("schema must parse");
    let again = parse(SCHEMA_DOC, "generate").expect("schema must parse");
    assert_eq!(
        serde_json::to_string(&schema_to_json_schema(&module).expect("jsonschema")).expect("json"),
        serde_json::to_string(&schema_to_json_schema(&again).expect("jsonschema")).expect("json"),
    );
    assert_eq!(
        schema_to_typescript(&module, "Config").expect("ts"),
        schema_to_typescript(&again, "Config").expect("ts"),
    );
    assert_eq!(
        schema_to_go(&module, "Config").expect("go"),
        schema_to_go(&again, "Config").expect("go"),
    );
    assert_eq!(
        schema_to_python(&module, "Config").expect("py"),
        schema_to_python(&again, "Config").expect("py"),
    );
    assert_eq!(
        schema_to_rust(&module, "Config").expect("rust"),
        schema_to_rust(&again, "Config").expect("rust"),
    );
}

#[test]
fn codegen_artifacts_carry_version_stamps() {
    use active_core::convert::CODEGEN_VERSION;
    assert_eq!(CODEGEN_VERSION, 2);
    let module = parse(SCHEMA_DOC, "generate").expect("schema must parse");
    let stamp = format!("(codegen v{CODEGEN_VERSION})");
    for output in [
        schema_to_typescript(&module, "Config").expect("ts"),
        schema_to_go(&module, "Config").expect("go"),
        schema_to_python(&module, "Config").expect("py"),
        schema_to_rust(&module, "Config").expect("rust"),
    ] {
        assert!(output.contains("Generated by Active"), "{output}");
        assert!(output.contains(&stamp), "{output}");
    }
    let schema = schema_to_json_schema(&module).expect("jsonschema");
    assert!(schema["$comment"]
        .as_str()
        .expect("comment")
        .contains(&stamp));
}

