#[test]
fn go_tags_skip_bool_required_and_ambiguous_oneof() {
    // validator `required` means non-zero, so Bool fields must not carry
    // it; members with spaces would make oneof ambiguous.
    let module = parse(
        "schema = { flag = Bool, choice = Enum(\"a b\", \"c\") }\n",
        "generate",
    )
    .expect("schema must parse");
    let go = schema_to_go(&module, "Config").expect("go");
    assert!(
        go.contains("`json:\"flag\"`"),
        "bool must carry no validate tag:\n{go}"
    );
    assert!(
        !go.contains("oneof="),
        "spaced members must skip oneof:\n{go}"
    );
    assert!(go.contains("// one of: a b, c"), "{go}");
}

#[test]
fn blob_codegen_emits_identity_shape_on_all_targets() {
    // PROPOSAL §1.1: every codegen target carries the blob identity
    // shape (hash, size, media type, taint) — never payload bytes.
    let module = parse(
        "schema = { logo = Blob(media_type = \"image/png\", max_size = 100) }\n",
        "generate",
    )
    .expect("schema must parse");
    let schema = schema_to_json_schema(&module).expect("jsonschema");
    assert_eq!(schema["properties"]["logo"]["x-active-blob"], true);
    assert_eq!(
        schema["properties"]["logo"]["x-active-media-type"],
        "image/png"
    );
    assert_eq!(schema["properties"]["logo"]["x-active-max-size"], 100);
    let ts = schema_to_typescript(&module, "Cfg").expect("ts");
    assert!(ts.contains("$active.blob"), "{ts}");
    assert!(!ts.contains("payload"), "{ts}");
    let go = schema_to_go(&module, "Cfg").expect("go");
    assert!(go.contains("ActiveBlob"), "{go}");
    assert!(!go.contains("payload"), "{go}");
    let rs = schema_to_rust(&module, "Cfg").expect("rs");
    assert!(rs.contains("pub struct ActiveBlob"), "{rs}");
    let py = schema_to_python(&module, "Cfg").expect("py");
    assert!(py.contains("class ActiveBlob(TypedDict)"), "{py}");
}
