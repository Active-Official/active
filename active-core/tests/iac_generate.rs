#[test]
fn pulumi_and_cdk_extend_the_typescript_contract() {
    let module = module();
    let pulumi = schema_to_pulumi(&module, "Config").expect("pulumi");
    assert!(
        pulumi.contains("export const ConfigSchema = z.object({"),
        "{pulumi}"
    );
    assert!(
        pulumi.contains("export interface PulumiConfigLike"),
        "{pulumi}"
    );
    assert!(
        pulumi.contains("getObject(key: string): unknown;"),
        "{pulumi}"
    );
    assert!(
        pulumi.contains("return ConfigSchema.parse(config.getObject(\"active\")) as Config;"),
        "{pulumi}"
    );
    let cdk = schema_to_cdk(&module, "Config").expect("cdk");
    assert!(cdk.contains("export interface CdkContextLike"), "{cdk}");
    assert!(
        cdk.contains("tryGetContext(key: string): unknown;"),
        "{cdk}"
    );
    assert!(
        cdk.contains("return ConfigSchema.parse(context.tryGetContext(\"active\")) as Config;"),
        "{cdk}"
    );
}

#[test]
fn zod_uses_active_format_patterns_not_the_narrower_library_ones() {
    // Active accepts `a@b.c`; zod's `.email()` does not (TLD length).
    // The binding must use Active's own regex so the contract matches.
    let ts = schema_to_typescript(&module(), "Config").expect("typescript");
    assert!(!ts.contains(".email()"), "{ts}");
    assert!(!ts.contains(".url()"), "{ts}");
    assert!(!ts.contains(".uuid()"), "{ts}");
    assert!(ts.contains("new RegExp(\"^[A-Za-z0-9._%+-]+@"), "{ts}");
}

#[test]
fn iac_targets_are_byte_stable() {
    for target in ["terraform", "pulumi", "cdk"] {
        let module = module();
        let first = match target {
            "terraform" => schema_to_terraform(&module, "Config"),
            "pulumi" => schema_to_pulumi(&module, "Config"),
            _ => schema_to_cdk(&module, "Config"),
        }
        .expect("generate");
        let again = parse(FLAT, "iac").expect("parse");
        let second = match target {
            "terraform" => schema_to_terraform(&again, "Config"),
            "pulumi" => schema_to_pulumi(&again, "Config"),
            _ => schema_to_cdk(&again, "Config"),
        }
        .expect("generate");
        assert_eq!(first, second, "{target} is not byte-stable");
        assert!(first.contains("Generated by Active"), "{target} header");
    }
}

