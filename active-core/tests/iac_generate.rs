#[test]
fn terraform_doubles_hcl_template_sequences() {
    // HCL treats `${` and `%{` as template syntax. Authored prose and
    // defaults must render literally (`$${`, `%%{`), not interpolate.
    let module = parse(
        "schema = { host = String(default = \"\\${x}\", description = \"bind \\${host} and %{ if }\") }\nhost = \"h\"\n",
        "iac-hcl-escape",
    )
    .expect("parse");
    let tf = schema_to_terraform(&module, "Config").expect("terraform");
    assert!(
        tf.contains("description = \"bind $${host} and %%{ if }\""),
        "{tf}"
    );
    assert!(tf.contains("default     = \"$${x}\""), "{tf}");
}

