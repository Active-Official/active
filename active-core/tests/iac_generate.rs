#[test]
fn terraform_scalar_array_elements_are_validated() {
    let module = parse(
        "schema = { ports = Array<Int(min = 1, max = 65535)> }\nports = [1]\n",
        "iac-array",
    );
    let Ok(module) = module else {
        // Element-argument syntax is grammar-dependent; a bare array must
        // still generate a list type.
        let module = parse(
            "schema = { ports = Array<Int> }\nports = [1]\n",
            "iac-array",
        )
        .expect("parse");
        let tf = schema_to_terraform(&module, "Config").expect("terraform");
        assert!(tf.contains("type     = list(number)"), "{tf}");
        return;
    };
    let tf = schema_to_terraform(&module, "Config").expect("terraform");
    assert!(tf.contains("type     = list(number)"), "{tf}");
    assert!(tf.contains("alltrue([for v in var.ports :"), "{tf}");
    assert!(tf.contains("v >= 1 && v <= 65535"), "{tf}");
}

