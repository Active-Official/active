//! L-P18: Pulumi / Terraform / CDK generate targets.
//!
//! Terraform is a native HCL `variables.tf` (scalars, scalar arrays, bare
//! and empty tables, bounds, descriptions, enums, formats, defaults,
//! sensitivity). A structured table is refused because Terraform's object
//! conversion silently discards attributes outside the type (verified with
//! `terraform plan` on 1.9.8), so representing one would drop keys.
//! Pulumi and CDK extend the proven TypeScript/zod target with a native
//! config/context reader.

use active_core::convert::{
    schema_to_cdk, schema_to_pulumi, schema_to_terraform, schema_to_typescript,
};
use active_core::parse;

const FLAT: &str = r#"schema = {
  host = String(default = "localhost", description = "bind address"),
  port = Int(min = 1, max = 65535, default = 8080),
  ratio = Float(min = 0.0, max = 1.0, default = 0.5),
  tls = Bool(default = false),
  timeout = Duration(min = 1ms, max = 5m, default = 30s),
  limit = Bytes(min = 1KiB, max = 2MiB, default = 1MiB),
  color = Enum("red", "green", default = "red"),
  email = String(format = "email", default = "a@b.c"),
  code = String(pattern = "^[a-z]+$", min_len = 2, max_len = 8, default = "ab"),
  tags = Array<String>,
  token = Secret,
  note = Null,
  anything = Any(default = null),
  empty = Table,
  closed_empty = Table { closed = true },
  meta = Any(default = { flag = true }),
}
"#;

fn module() -> active_core::ir::Module {
    parse(FLAT, "iac").expect("must parse")
}

#[test]
fn terraform_covers_scalar_features_exactly() {
    let tf = schema_to_terraform(&module(), "Config").expect("terraform");
    assert!(
        tf.starts_with("# Generated by Active"),
        "generated header missing:\n{tf}"
    );
    assert!(tf.contains("variable \"host\" {"), "{tf}");
    assert!(tf.contains("description = \"bind address\""), "{tf}");
    assert!(tf.contains("default     = \"localhost\""), "{tf}");
    // Int: integrality plus both bounds.
    assert!(
        tf.contains("condition     = floor(var.port) == var.port"),
        "{tf}"
    );
    assert!(tf.contains("condition     = var.port >= 1"), "{tf}");
    assert!(tf.contains("condition     = var.port <= 65535"), "{tf}");
    // Duration and Bytes are canonical integer magnitudes.
    assert!(tf.contains("default  = 30000"), "{tf}");
    assert!(tf.contains("default  = 1048576"), "{tf}");
    assert!(
        tf.contains("a canonical millisecond magnitude must be a whole number"),
        "{tf}"
    );
    assert!(tf.contains("var.timeout >= 1"), "{tf}");
    assert!(tf.contains("var.timeout <= 300000"), "{tf}");
    assert!(tf.contains("var.limit >= 1024"), "{tf}");
    assert!(tf.contains("var.limit <= 2097152"), "{tf}");
    // Enum, format, pattern, lengths.
    assert!(
        tf.contains("contains([\"red\", \"green\"], var.color)"),
        "{tf}"
    );
    assert!(tf.contains("can(regex(\"^[A-Za-z0-9._%+-]+@"), "{tf}");
    assert!(tf.contains("can(regex(\"^[a-z]+$\", var.code))"), "{tf}");
    assert!(tf.contains("length(var.code) >= 2"), "{tf}");
    assert!(tf.contains("length(var.code) <= 8"), "{tf}");
    // Secret is sensitive; Null is optional and null-only.
    assert!(tf.contains("sensitive = true"), "{tf}");
    let note = tf
        .split("variable \"note\" {")
        .nth(1)
        .and_then(|rest| rest.split('}').next())
        .expect("note block");
    assert!(note.contains("default  = null"), "{note}");
    assert!(note.contains("nullable = true"), "{note}");
    assert!(note.contains("var.note == null"), "{note}");
    // Bare/open and empty closed tables, and an object-valued Any default
    // (quoted keys are valid HCL object-constructor syntax).
    assert!(tf.contains("type     = map(any)"), "{tf}");
    assert!(tf.contains("length(var.closed_empty) == 0"), "{tf}");
    assert!(tf.contains("default  = { \"flag\" = true }"), "{tf}");
    // No structured tables appear in this fixture.
    assert!(!tf.contains("object({"), "{tf}");
}

#[test]
fn terraform_refuses_structured_tables() {
    let module = parse(
        "schema = { server = Table { host = String } }\nserver = { host = \"h\" }\n",
        "iac-table",
    )
    .expect("parse");
    let error = schema_to_terraform(&module, "Config").expect_err("structured tables refuse");
    assert!(error.contains("structured table"), "{error}");
    assert!(error.contains("discards attributes"), "{error}");
}

#[test]
fn terraform_refuses_features_it_cannot_state() {
    let cases = [
        (
            "schema = { b = Blob }\nb = blob(\"text/plain\", \"x\")\n",
            "Blob",
        ),
        (
            "schema = { v = OneOf(Int, String) }\nv = 1\n",
            "OneOf",
        ),
        (
            "schema = { tls = Bool, cert = String(requires = \"tls\") }\ntls = true\ncert = \"c\"\n",
            "requires",
        ),
        (
            "let cap = 10\nschema = { p = Int(max = cap) }\np = 1\n",
            "",
        ),
    ];
    for (source, needle) in cases {
        let module = parse(source, "iac-refuse").expect("parse");
        match schema_to_terraform(&module, "Config") {
            Ok(output) => {
                // The let-bound bound is static and representable.
                assert!(
                    needle.is_empty(),
                    "unexpected refusal for {source}:\n{output}"
                );
                assert!(output.contains("var.p <= 10"), "{output}");
            }
            Err(error) => {
                assert!(
                    !needle.is_empty(),
                    "unexpected refusal for {source}: {error}"
                );
                assert!(
                    error.contains(needle),
                    "refusal should name {needle}: {error}"
                );
            }
        }
    }
}

